export type ApplyMode = "same" | "adapted" | "manual";

export interface RulebookSource {
  name: string;
  /** API · API(인허가 원장) · 지도 검색 · 담당자 지정 · 연결 필요 */
  kind: string;
  note: string;
}

/**
 * 문단 하나. 문자열이면 문장마다 줄을 바꿔 보여 주고, 항목 목록이면 항목마다
 * 한 줄로 보여 준다(번호·배점·등급표처럼 나열되는 것은 목록으로 쓴다).
 */
export type RulebookParagraph = string | { lead?: string; items: string[] };

export interface RulebookItem {
  id: string;
  title: string;
  /** 왼쪽 목록에 붙는 짧은 부제(임계거리·배점). */
  tag: string;
  /** LH 기준 — 법령·심사표·회신에 적힌 그대로. 문단 배열. */
  lhCriteria: RulebookParagraph[];
  /** 이 앱의 적용. mode 가 same 이면 그대로, adapted 면 다르게(사유 필수), manual 이면 수기. */
  apply: { mode: ApplyMode; paragraphs: RulebookParagraph[] };
  sources: RulebookSource[];
}

export interface RulebookGroup {
  id: string;
  title: string;
  items: RulebookItem[];
}

